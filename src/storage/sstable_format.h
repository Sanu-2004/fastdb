#ifndef FASTDB_SSTABLE_FORMAT_H
#define FASTDB_SSTABLE_FORMAT_H

#include "sstable.h"

enum {
    SST_VERSION = 1,
    SST_PARTITIONED_VERSION = 2,
    SST_HEADER_BYTES = 32,
    SST_BLOCK_HEADER_BYTES = 16,
    SST_INDEX_HEADER_BYTES = 4,
    SST_INDEX_ENTRY_BYTES = 16,
    SST_MIN_INDEX_ENTRY_BYTES = SST_INDEX_ENTRY_BYTES + 1,
    SST_PROPERTIES_HEADER_BYTES = 48,
    SST_FOOTER_BYTES = 56,
    SST_CRC_BYTES = 4,
    SST_OFFSET_BYTES = 4,
    SST_MIN_ROW_BYTES = FDB_RECORD_HEADER_BYTES + 1 + SST_OFFSET_BYTES,
    SST_FEATURE_BLOOM = 1
};

#define SST_MAGIC "FASTSST\0"
#define SST_FOOTER_MAGIC "FDBSSTF1"
#define SST_PARTITIONED_FOOTER_MAGIC "FDBSSTF2"
#define SST_BLOCK_MAGIC UINT32_C(0x314b4c42)
#define SST_LZ4_BLOCK_MAGIC UINT32_C(0x42345a4c)

#endif
